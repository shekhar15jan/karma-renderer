/**
 * Generates src/icons/techIcons.generated.ts from assets/icon-reference.
 *
 * Widgets render inside the Remotion/Chromium bundle where `fs` is unavailable,
 * so icon geometry has to be baked into a module at build time rather than read
 * from disk at render time. Only slugs listed in the manifest are emitted, which
 * keeps the bundle small even though simple-icons ships 3400+ brands.
 *
 * Resolution per slug:
 *   1. assets/icon-reference/<slug>.svg  — used verbatim, original colours kept
 *   2. manifest `si` key                 — simple-icons path, tintable monochrome
 *   3. neither                           — omitted; the widget falls back to a monogram
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const ICON_DIR = path.join(ROOT, "assets", "icon-reference");
const MANIFEST = path.join(ICON_DIR, "manifest.json");
const OUT = path.join(ROOT, "src", "icons", "techIcons.generated.ts");

function loadSimpleIcons() {
  try {
    return require("simple-icons");
  } catch {
    console.warn("[tech-icons] simple-icons not installed — only local overrides will be emitted");
    return null;
  }
}

/** Pulls viewBox + inner markup out of a standalone SVG file so it can be re-hosted. */
function parseSvgFile(file) {
  const raw = fs.readFileSync(file, "utf8");
  const viewBox = (raw.match(/viewBox\s*=\s*["']([^"']+)["']/i) || [])[1] || "0 0 24 24";
  const inner = (raw.match(/<svg[^>]*>([\s\S]*?)<\/svg>/i) || [])[1];
  if (!inner || !inner.trim()) throw new Error(`no <svg> body found in ${path.basename(file)}`);
  const body = inner
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/<\?xml[\s\S]*?\?>/g, "")
    .replace(/\s+/g, " ")
    .trim();
  return { viewBox, body };
}

function siKeyFor(name) {
  return "si" + name.charAt(0).toUpperCase() + name.slice(1);
}

function main() {
  const manifest = JSON.parse(fs.readFileSync(MANIFEST, "utf8"));
  const si = loadSimpleIcons();

  const defs = [];
  const aliasPairs = [];
  const missing = [];

  for (const entry of manifest.icons) {
    const overrideFile = path.join(ICON_DIR, entry.file || `${entry.slug}.svg`);
    let resolved = null;

    if (fs.existsSync(overrideFile)) {
      try {
        const { viewBox, body } = parseSvgFile(overrideFile);
        resolved = { viewBox, body, monochrome: false, source: "override" };
      } catch (e) {
        console.warn(`[tech-icons] ${entry.slug}: ${e.message}`);
      }
    }

    if (!resolved && entry.si && si) {
      const icon = si[siKeyFor(entry.si)];
      if (icon) {
        resolved = {
          viewBox: "0 0 24 24",
          body: `<path d="${icon.path}"/>`,
          monochrome: true,
          source: "simple-icons",
          hex: icon.hex,
        };
      }
    }

    if (!resolved) {
      missing.push(entry.slug);
      continue;
    }

    const hex = (entry.hex || resolved.hex || "6B7280").replace(/^#/, "");
    defs.push({
      slug: entry.slug,
      title: entry.title,
      category: entry.category,
      hex,
      viewBox: resolved.viewBox,
      body: resolved.body,
      monochrome: resolved.monochrome,
      source: resolved.source,
    });
    for (const a of entry.aliases || []) aliasPairs.push([a, entry.slug]);
  }

  const esc = (s) => s.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
  const lines = [];
  lines.push("/* AUTO-GENERATED by scripts/build-tech-icons.js — do not edit by hand.");
  lines.push(" * Regenerate with: npm run build:icons");
  lines.push(` * ${defs.length} icons emitted from assets/icon-reference/manifest.json */`);
  lines.push("");
  lines.push("export interface TechIconDef {");
  lines.push("  slug: string;");
  lines.push("  title: string;");
  lines.push("  category: string;");
  lines.push("  /** Brand colour, no leading #. */");
  lines.push("  hex: string;");
  lines.push("  viewBox: string;");
  lines.push("  /** Inner SVG markup. */");
  lines.push("  body: string;");
  lines.push("  /** True when the mark is a single silhouette and may be tinted. */");
  lines.push("  monochrome: boolean;");
  lines.push('  source: "override" | "simple-icons";');
  lines.push("}");
  lines.push("");
  lines.push("export const TECH_ICONS: Record<string, TechIconDef> = {");
  for (const d of defs) {
    lines.push(
      `  "${d.slug}": { slug: "${d.slug}", title: "${esc(d.title)}", category: "${d.category}", hex: "${d.hex}", viewBox: "${d.viewBox}", monochrome: ${d.monochrome}, source: "${d.source}", body: "${esc(d.body)}" },`
    );
  }
  lines.push("};");
  lines.push("");
  lines.push("export const TECH_ALIASES: Record<string, string> = {");
  for (const [a, s] of aliasPairs) lines.push(`  "${a}": "${s}",`);
  lines.push("};");
  lines.push("");
  lines.push("/** Resolves a slug, alias, or loose label (\"Spring Boot\", \"K8s\") to a mark. */");
  lines.push("export function lookupTechIcon(name?: string | null): TechIconDef | null {");
  lines.push("  if (!name) return null;");
  lines.push("  const k = String(name).trim().toLowerCase().replace(/[\\s_.]+/g, '-');");
  lines.push("  if (TECH_ICONS[k]) return TECH_ICONS[k];");
  lines.push("  if (TECH_ALIASES[k]) return TECH_ICONS[TECH_ALIASES[k]] ?? null;");
  lines.push("  const bare = k.replace(/-/g, '');");
  lines.push("  for (const def of Object.values(TECH_ICONS)) {");
  lines.push("    if (def.slug.replace(/-/g, '') === bare) return def;");
  lines.push("  }");
  lines.push("  return null;");
  lines.push("}");
  lines.push("");

  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, lines.join("\n"), "utf8");

  const overrides = defs.filter((d) => d.source === "override").length;
  console.log(
    `[tech-icons] ${defs.length} icons (${overrides} local override, ${defs.length - overrides} simple-icons) -> src/icons/techIcons.generated.ts`
  );
  if (missing.length) {
    console.log(`[tech-icons] ${missing.length} awaiting a local SVG: ${missing.join(", ")}`);
  }
}

main();
